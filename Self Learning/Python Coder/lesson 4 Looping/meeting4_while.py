# dari 0 ke 10 vertikal
i = 0 
while i < 10 :
    print (i)
    i += 1

# dari 0 ke 10 horizontal
i = 0 
while i < 10:
    print(i, end=" ")  # Cetak angka ke samping dengan pemisah spasi
    i += 1

#dari 10 ke 0 vertikal
i = 10 
while not i < 0 :
    print (i)
    i -= 1
    
