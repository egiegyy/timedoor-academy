# menggunakan for loop vertikal
for counter in range(5):
    print("How are you?!" )
    
# menggunakan for loop horizontal
for counter in range(5):
    print("How are you?!", end=" ")
    
# menggunakan for loop dengan variabel vertikal
name = "Egyn"
for counter in range(5):
    print("Hello " + name + " ! ")

# menggunakan for loop dengan variabel horizontal
name = "Egyn"
for counter in range(5):
    print("Hello " + name + " ! ", end=" ")
    
# menggunakan for loop dengan variabel dan range vertikal
for x in range(10):
    print(x)
    
# Menampilkan angka secara horizontal (dipisahkan spasi)
for x in range(10):
    print(x, end=" ")