age = 25  # Simpan nilai umur (25) ke variabel age

if age < 18:  # Jika umur di bawah 18 tahun
    print("You are still underage.")  # Cetak: Masih di bawah umur
elif age >= 18 and age < 65:  # Jika umur antara 18 sampai 64 tahun
    print("You are an adult.")  # Cetak: Sudah dewasa
else:  # Jika umur 65 tahun ke atas
    print("You are a senior citizen.")  # Cetak: Lansia (senior)