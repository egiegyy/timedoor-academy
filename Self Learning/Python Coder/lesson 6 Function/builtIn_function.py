# contoh 1
number = [53,23,9,70,12]

print("Maximum value : " + str(max(number))) # max() mencari nilai maksimal dalam list number
print("Minimum value : " + str(min(number))) # min() mencari nilai minimal dalam list number
print("words in capital letters".upper()) # upper() mengubah seluruh huruf string menjadi huruf kapital
print("words in lower case".lower()) # lower() mengubah seluruh huruf string menjadi huruf kecil

